import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

/**
 * Regenerates src/core/zip-centroids.ts from the Census Bureau's ZCTA
 * gazetteer (public domain; ADR-0015 as amended 2026-10-26):
 *
 *   curl -O https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2025_Gazetteer/2025_Gaz_zcta_national.zip
 *   unzip 2025_Gaz_zcta_national.zip
 *   npx tsx scripts/zip-centroids.ts 2025_Gaz_zcta_national.txt
 *
 * Derived data: never edit the output by hand — rerun this on a newer file.
 * Four decimals is ~11 m, far finer than a zip's own extent.
 */
const [input] = process.argv.slice(2);
if (!input) throw new Error("usage: tsx scripts/zip-centroids.ts <Gaz_zcta_national.txt>");

const lines = readFileSync(input, "utf8").trim().split("\n");
const header = lines[0].split("|").map((h) => h.trim());
const [zip, lat, lon] = ["GEOID", "INTPTLAT", "INTPTLONG"].map((name) => {
  const at = header.indexOf(name);
  if (at < 0) throw new Error(`no ${name} column in ${input}`);
  return at;
});

const rows = lines.slice(1).map((line) => {
  const cells = line.split("|").map((c) => c.trim());
  if (!/^\d{5}$/.test(cells[zip])) throw new Error(`bad zip: ${line}`);
  return `${cells[zip]} ${Number(cells[lat]).toFixed(4)} ${Number(cells[lon]).toFixed(4)}`;
});
rows.sort();

const out = path.resolve("src/core/zip-centroids.ts");
writeFileSync(
  out,
  `// Generated by scripts/zip-centroids.ts from the Census ZCTA gazetteer
// (${path.basename(input)}, public domain) — never edit by hand (ADR-0015 as
// amended 2026-10-26). One "zip lat lon" per line, sorted by zip.
export const ZIP_CENTROIDS = \`${rows.join("\n")}\`;
`,
);
console.log(`wrote ${rows.length} zips to ${out}`);
